"""Render every character and export:

  PetsAssets/{id}_{anim}-{n}.png   individual frames, Pet Therapy naming
  Species/{id}.json                Pet Therapy species definition
  preview/strips/{id}_{anim}.png   one horizontal strip per animation (for the preview)
  preview/manifest.js              metadata the preview page reads
  docs/roster.png                  line-up of everyone

Usage: python3 tools/sprites/build.py [character_id ...]"""

import json
import shutil
import sys
from pathlib import Path

from PIL import Image

import anims
import frames
from characters import BY_ID, CHARACTERS

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / 'PetsAssets'
SPECIES = ROOT / 'Species'
STRIPS = ROOT / 'preview' / 'strips'
DOCS = ROOT / 'docs'

CAPABILITIES = [
    'AnimatedSprite', 'AnimationsProvider', 'AutoRespawn', 'BounceOnLateralCollisions',
    'Draggable', 'FlipHorizontallyWhenGoingLeft', 'Gravity', 'LinearMovement',
    'PetsSpritesProvider', 'AnimationsScheduler', 'Rotating', 'ShowsMenuOnRightClick',
    'TrapEscaper', 'PlatformLooper', 'TeleportationPortal',
]


def species_json(ch, built):
    animations = []
    for a in built:
        if a.id in ('walk', 'drag'):
            continue
        entry = {'id': a.id, 'position': 'fromEntityBottomLeft', 'requiredLoops': a.loops}
        w, h = a.size
        if (w, h) != (1, 1):
            entry['size'] = [round(w, 3), round(h, 3)]
        if a.moving:
            entry['isMoving'] = True
        animations.append(entry)
    return {
        'animations': animations,
        'capabilities': CAPABILITIES,
        'dragPath': 'drag',
        'fps': 10,
        'zIndex': 0,
        'scale': 1,
        'tags': ['naruto', ch.era],
        'id': ch.id,
        'groupCategory': ch.group,
        'colorHex': ch.color.lstrip('#'),
        'movementPath': 'walk',
        'speed': ch.speed,
    }


def export(ch):
    built = anims.build_all(ch)
    drawn = frames.apply_drawings(ch, built)
    # drop stale frames for this character (but not e.g. naruto_shippuden_* for naruto)
    others = [c.id for c in CHARACTERS if c.id != ch.id and c.id.startswith(ch.id + '_')]
    for d in (ASSETS, STRIPS):
        for old in d.glob(f'{ch.id}_*.png'):
            if not any(old.name.startswith(o + '_') for o in others):
                old.unlink()
    meta = {'id': ch.id, 'name': ch.name, 'era': ch.era, 'color': ch.color,
            'tagline': ch.tagline, 'speed': ch.speed, 'group': ch.group, 'animations': {}}
    for a in built:
        for n, fr in enumerate(a.frames):
            fr.image().save(ASSETS / f'{ch.id}_{a.id}-{n}.png', optimize=True)
        fw, fh = a.frames[0].w, a.frames[0].h
        strip = Image.new('RGBA', (fw * len(a.frames), fh))
        for n, fr in enumerate(a.frames):
            strip.paste(fr.image(), (n * fw, 0))
        strip.save(STRIPS / f'{ch.id}_{a.id}.png')
        meta['animations'][a.id] = {
            'frames': len(a.frames), 'w': fw, 'h': fh, 'anchorX': a.anchor_x,
            'loops': a.loops, 'moving': a.moving, 'label': a.label, 'kind': a.kind,
        }
    (SPECIES / f'{ch.id}.json').write_text(json.dumps(species_json(ch, built), indent=2) + '\n')
    total = sum(len(a.frames) for a in built)
    note = f'  (drawn: {", ".join(drawn)})' if drawn else ''
    print(f'{ch.id:22s} {len(built):2d} animations, {total:4d} frames{note}')
    return meta


def roster(chars):
    from body import H, Pose, render
    pad = 10
    shots = []
    for ch in chars:
        im = render(ch, Pose())[0].image()
        x0, _, x1, _ = im.getbbox()
        shots.append(im.crop((x0, 0, x1, H)))
    img = Image.new('RGBA', (sum(s.width + pad for s in shots) + pad, H + pad * 2), (0, 0, 0, 0))
    x = pad
    for s in shots:
        img.alpha_composite(s, (x, pad))
        x += s.width + pad
    img.save(DOCS / 'roster.png', optimize=True)


def main(ids):
    for d in (ASSETS, SPECIES, STRIPS, DOCS):
        d.mkdir(parents=True, exist_ok=True)
    chars = [BY_ID[i] for i in ids] if ids else CHARACTERS
    if not ids:
        for d in (ASSETS, STRIPS):
            shutil.rmtree(d)
            d.mkdir(parents=True)
        for f in SPECIES.glob('*.json'):
            f.unlink()
    manifest_path = ROOT / 'preview' / 'manifest.js'
    metas = {}
    if ids and manifest_path.exists():
        txt = manifest_path.read_text()
        metas = {m['id']: m for m in json.loads(txt[txt.index('['):txt.rindex(']') + 1])}
    for ch in chars:
        metas[ch.id] = export(ch)
    ordered = [metas[c.id] for c in CHARACTERS if c.id in metas]
    manifest_path.write_text('// Generated by tools/sprites/build.py - do not edit.\n'
                             'window.PETS = ' + json.dumps(ordered, indent=1) + ';\n')
    roster(CHARACTERS)


if __name__ == '__main__':
    main(sys.argv[1:])
